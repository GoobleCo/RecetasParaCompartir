create or replace function public.current_role_name()
returns public.user_role language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = auth.uid();
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select role = 'admin' from public.profiles where id = auth.uid()), false);
$$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select role in ('admin', 'moderator') from public.profiles where id = auth.uid()), false);
$$;

create or replace function public.can_view_recipe(rid uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.recipes r
    where r.id = rid and (r.is_public or r.author_id = auth.uid() or public.is_staff())
  );
$$;

