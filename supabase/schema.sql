  for each row execute function public.notify_on_new_challenge();

-- 6. PUSH: cada notificación insertada se envía al celular -------------
create or replace function public.push_notification()
returns trigger language plpgsql security definer set search_path = '' as $$
declare msgs jsonb;
begin
  select jsonb_agg(jsonb_build_object(
           'to', t.token, 'title', new.title, 'body', new.body, 'sound', 'default', 'channelId', 'default',
           'data', jsonb_build_object('notificationId', new.id, 'type', new.type,
                                      'challengeId', new.challenge_id, 'actorId', new.actor_id)))
    into msgs
  from public.push_tokens t where t.user_id = new.user_id;
  if msgs is not null then
    -- pg_net hace el POST de forma ASÍNCRONA: no frena la operación del usuario
    perform net.http_post(
      url     := 'https://exp.host/--/api/v2/push/send',
      body    := msgs,
      headers := '{"Content-Type": "application/json", "Accept": "application/json"}'::jsonb);
  end if;
  return new;
exception when others then
  raise warning 'No se pudo enviar el push: %', sqlerrm;
  return new;
end $$;
drop trigger if exists notifications_push on public.notifications;
create trigger notifications_push after insert on public.notifications
  for each row execute function public.push_notification();

-- 7. PARTIDAS VALIDADAS EN EL SERVIDOR ---------------------------------
-- El cliente NUNCA manda el puntaje. Manda lo que hizo (flechas correctas, rondas,
-- rondas perfectas, tiempo sobrante) y el servidor:
--   1) verifica que sea físicamente posible según el tiempo real transcurrido,
--   2) calcula el puntaje con la misma fórmula que muestra la app,
--   3) actualiza los rankings y avisa a quien perdió el primer puesto.

create or replace function public.ensure_daily_challenge(p_day date)
returns bigint language plpgsql security definer set search_path = '' as $$
declare s bigint;
begin
  insert into public.daily_challenges (day, seed)
  values (p_day, floor(random() * 2147483647)::bigint)
  on conflict (day) do nothing;
  select seed into s from public.daily_challenges where day = p_day;
  return s;
end $$;

create or replace function public.start_run(p_mode text, p_challenge uuid default null)
returns json language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  v_seed bigint; v_round_ms integer; v_max integer; v_day date; v_ids integer[]; v_title text;
  v_run uuid; v_protocols json;
begin
  if uid is null then raise exception 'No autenticado' using errcode = '42501'; end if;
  if (select count(*) from public.runs where user_id = uid and started_at > now() - interval '1 minute') >= 20 then
    raise exception 'Demasiadas partidas seguidas. Esperá un minuto.' using errcode = 'P0001';
  end if;

  if p_mode = 'classic' then
    v_seed := floor(random() * 2147483647)::bigint; v_round_ms := 10000; v_max := null; v_title := 'Modo clásico';
    select array_agg(id order by id) into v_ids from public.protocols where active;
  elsif p_mode = 'daily' then
    v_day := public.game_today();
    v_seed := public.ensure_daily_challenge(v_day); v_round_ms := 9000; v_max := 10; v_title := 'Desafío diario';
    select array_agg(id order by id) into v_ids from public.protocols where active;
  elsif p_mode = 'challenge' then
    if p_challenge is null or not public.can_view_challenge(p_challenge) then
      raise exception 'El desafío no existe o es privado' using errcode = 'P0002';
    end if;
    select c.seed, c.round_time_s * 1000, c.rounds, c.title,
           array(select p.id from public.protocols p where p.id = any (c.protocol_ids) order by p.id)
      into v_seed, v_round_ms, v_max, v_title, v_ids
    from public.challenges c where c.id = p_challenge;
  else
    raise exception 'Modo de juego inválido' using errcode = '22023';
  end if;

  if coalesce(cardinality(v_ids), 0) < 2 then
    raise exception 'No hay suficientes protocolos para jugar' using errcode = 'P0001';
  end if;

  insert into public.runs (user_id, mode, challenge_id, day, seed, round_time_ms, max_rounds)
  values (uid, p_mode, case when p_mode = 'challenge' then p_challenge end, v_day, v_seed, v_round_ms, v_max)
  returning id into v_run;

  select json_agg(json_build_object('id', p.id, 'name', p.name, 'code', p.code, 'icon', p.icon,
                                    'category', p.category) order by p.id)
    into v_protocols
  from public.protocols p where p.id = any (v_ids);

  return json_build_object('run_id', v_run, 'mode', p_mode, 'title', v_title, 'seed', v_seed,
                           'round_time_ms', v_round_ms, 'max_rounds', v_max, 'protocols', v_protocols);
end $$;

-- Fórmula de puntaje (la misma que lib/game.ts)
create or replace function public.compute_score(p_arrows int, p_rounds int, p_perfect int, p_time_bonus_ms int)
returns integer language sql immutable set search_path = '' as $$
  select p_arrows * 10 + 50 * p_rounds + 25 * p_rounds * (p_rounds + 1) / 2 + p_perfect * 100 + p_time_bonus_ms / 100;
$$;

create or replace function public.finish_run(p_run uuid, p_arrows int, p_rounds int, p_perfect int,
                                             p_time_bonus_ms int, p_mistakes int)
returns json language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  r public.runs;
  elapsed_ms numeric;
  v_score integer; v_completed boolean; v_reason text;
  v_boards text[]; v_board text; v_main text; v_label text;
  prev_best integer; leader record; me text;
  v_best integer; v_rank bigint; v_new_record boolean := false;
begin
  if uid is null then raise exception 'No autenticado' using errcode = '42501'; end if;
  select * into r from public.runs where id = p_run and user_id = uid for update;
  if r.id is null then raise exception 'La partida no existe' using errcode = 'P0002'; end if;
  if r.status <> 'started' then raise exception 'Esta partida ya fue registrada' using errcode = 'P0001'; end if;

  elapsed_ms := extract(epoch from (now() - r.started_at)) * 1000;

  -- Controles anti-trampa
  if p_arrows < 0 or p_rounds < 0 or p_perfect < 0 or p_time_bonus_ms < 0 or p_mistakes < 0 then
    v_reason := 'valores negativos';
  elsif r.max_rounds is not null and p_rounds > r.max_rounds then
    v_reason := 'más rondas que las del desafío';
  elsif p_perfect > p_rounds then
    v_reason := 'más rondas perfectas que rondas';
  elsif p_time_bonus_ms > p_rounds::bigint * r.round_time_ms then
    v_reason := 'tiempo sobrante imposible';
  elsif p_arrows < p_rounds * 9 then
    v_reason := 'flechas insuficientes para esas rondas';
  elsif p_arrows > elapsed_ms / 1000 * 15 + 20 then
    v_reason := 'demasiadas flechas para el tiempo jugado';
  elsif elapsed_ms > 3 * 3600 * 1000 then
    v_reason := 'partida vencida';
  end if;

  if v_reason is not null then
    update public.runs set status = 'rejected', finished_at = now(), reject_reason = v_reason where id = r.id;
    return json_build_object('rejected', true, 'reason', v_reason);
  end if;

  v_score := public.compute_score(p_arrows, p_rounds, p_perfect, p_time_bonus_ms);
  v_completed := r.max_rounds is not null and p_rounds >= r.max_rounds;

  update public.runs set status = 'finished', finished_at = now(), arrows = p_arrows, rounds_cleared = p_rounds,
    perfect_rounds = p_perfect, time_bonus_ms = p_time_bonus_ms, mistakes = p_mistakes,
    score = v_score, completed = v_completed
  where id = r.id;

  if r.mode = 'classic' then
    v_main := 'classic';
    v_boards := array['classic', 'classic:week:' || public.game_week(public.game_today())];
    v_label := 'el ranking Clásico';
  elsif r.mode = 'daily' then
    v_main := 'daily:' || r.day::text;
    v_boards := array[v_main];
    v_label := 'el Desafío diario';
  else
    v_main := 'challenge:' || r.challenge_id::text;
    v_boards := array[v_main];
    select '«' || title || '»' into v_label from public.challenges where id = r.challenge_id;
    update public.challenges set play_count = play_count + 1 where id = r.challenge_id;
  end if;

  select username into me from public.profiles where id = uid;

  foreach v_board in array v_boards loop
    select score into prev_best from public.best_scores where user_id = uid and board = v_board;
    if prev_best is null or v_score > prev_best then
      if v_board = v_main then v_new_record := true; end if;
      -- ¿Quién era el primero antes de este puntaje?
      select b.user_id, b.score, p.notify_beaten into leader
      from public.best_scores b join public.profiles p on p.id = b.user_id
      where b.board = v_board order by b.score desc, b.achieved_at asc limit 1;

      insert into public.best_scores (user_id, board, score, run_id, achieved_at)
      values (uid, v_board, v_score, r.id, now())
      on conflict (user_id, board) do update
        set score = excluded.score, run_id = excluded.run_id, achieved_at = excluded.achieved_at;

      if leader.user_id is not null and leader.user_id <> uid and v_score > leader.score
         and leader.notify_beaten and v_board not like 'classic:week:%' then
        insert into public.notifications (user_id, actor_id, type, title, body, challenge_id)
        values (leader.user_id, uid, 'beaten', '¡Perdiste el primer puesto! ⚠️',
                '@' || me || ' te superó en ' || coalesce(v_label, 'un ranking') || ' con ' || v_score
                || ' puntos. ¡Recuperalo!', r.challenge_id);
      end if;
    end if;
  end loop;

  select score into v_best from public.best_scores where user_id = uid and board = v_main;
  select 1 + count(*) into v_rank from public.best_scores where board = v_main and score > v_best;

  return json_build_object('rejected', false, 'score', v_score, 'best', v_best, 'new_record', v_new_record,
                           'previous_best', prev_best, 'rank', v_rank, 'completed', v_completed, 'board', v_main);
end $$;

