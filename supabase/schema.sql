create or replace function public.notify_on_comment()
returns trigger language plpgsql security definer set search_path = '' as $$
declare ch record; actor text;
begin
  select c.id, c.title, c.author_id, p.notify_comments into ch
  from public.challenges c join public.profiles p on p.id = c.author_id where c.id = new.challenge_id;
  if ch.author_id is null or ch.author_id = new.user_id or not ch.notify_comments then return new; end if;
  select username into actor from public.profiles where id = new.user_id;
  insert into public.notifications (user_id, actor_id, type, title, body, challenge_id)
  values (ch.author_id, new.user_id, 'comment', 'Nuevo comentario 💬',
          '@' || actor || ' comentó «' || ch.title || '»: ' || left(new.body, 80), ch.id);
  return new;
end $$;
drop trigger if exists comments_notify on public.comments;
create trigger comments_notify after insert on public.comments
  for each row execute function public.notify_on_comment();

create or replace function public.notify_on_rating()
returns trigger language plpgsql security definer set search_path = '' as $$
declare ch record; actor text;
begin
  if tg_op = 'UPDATE' and new.stars = old.stars then return new; end if;
  select c.id, c.title, c.author_id, p.notify_ratings into ch
  from public.challenges c join public.profiles p on p.id = c.author_id where c.id = new.challenge_id;
  if ch.author_id is null or ch.author_id = new.user_id or not ch.notify_ratings then return new; end if;
  select username into actor from public.profiles where id = new.user_id;
  insert into public.notifications (user_id, actor_id, type, title, body, challenge_id)
  values (ch.author_id, new.user_id, 'rating', 'Nueva valoración ⭐',
          '@' || actor || ' le dio ' || new.stars || ' estrella' || case when new.stars = 1 then '' else 's' end
          || ' a «' || ch.title || '»', ch.id);
  return new;
end $$;
drop trigger if exists ratings_notify on public.ratings;
