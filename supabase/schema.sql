create or replace function public.notify_on_new_challenge()
returns trigger language plpgsql security definer set search_path = '' as $$
declare actor text;
begin
  if not new.is_public then return new; end if;
  select username into actor from public.profiles where id = new.author_id;
  insert into public.notifications (user_id, actor_id, type, title, body, challenge_id)
  select f.follower_id, new.author_id, 'new_challenge', 'Nuevo desafío 🎯',
         '@' || actor || ' publicó «' || new.title || '». ¿Te animás?', new.id
  from public.follows f join public.profiles p on p.id = f.follower_id
  where f.following_id = new.author_id and p.notify_new_challenges;
  return new;
end $$;
