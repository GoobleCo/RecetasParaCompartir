-- 5.3 Validar que los protocolos de un desafío existan (un array no tiene FK)
create or replace function public.validate_challenge_protocols()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.protocol_ids := array(select distinct x from unnest(new.protocol_ids) x where x is not null order by 1);
  if cardinality(new.protocol_ids) < 2 then
    raise exception 'El desafío necesita al menos 2 protocolos distintos' using errcode = '23514';
  end if;
  if exists (select 1 from unnest(new.protocol_ids) pid
             where not exists (select 1 from public.protocols p where p.id = pid)) then
    raise exception 'El desafío tiene protocolos inexistentes' using errcode = '23503';
  end if;
  return new;
end $$;
drop trigger if exists challenges_validate on public.challenges;
create trigger challenges_validate before insert or update of protocol_ids on public.challenges
  for each row execute function public.validate_challenge_protocols();

-- Al borrar un protocolo se quita de los desafíos (o se impide si dejaría alguno inválido)
create or replace function public.protocol_before_delete()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if exists (select 1 from public.challenges c
             where old.id = any (c.protocol_ids) and cardinality(c.protocol_ids) <= 2) then
    raise exception 'No se puede eliminar: hay desafíos que quedarían con menos de 2 protocolos. Desactivalo en su lugar.'
      using errcode = '23503';
  end if;
  update public.challenges set protocol_ids = array_remove(protocol_ids, old.id) where old.id = any (protocol_ids);
  return old;
end $$;
drop trigger if exists protocols_before_delete on public.protocols;
create trigger protocols_before_delete before delete on public.protocols
  for each row execute function public.protocol_before_delete();

-- 5.4 Contadores de cada desafío
create or replace function public.refresh_challenge_counters()
returns trigger language plpgsql security definer set search_path = '' as $$
declare cid uuid := coalesce(new.challenge_id, old.challenge_id);
begin
  update public.challenges c set
    avg_rating     = coalesce((select round(avg(stars)::numeric, 2) from public.ratings where challenge_id = cid), 0),
    rating_count   = (select count(*) from public.ratings   where challenge_id = cid),
    comment_count  = (select count(*) from public.comments  where challenge_id = cid),
    favorite_count = (select count(*) from public.favorites where challenge_id = cid)
  where c.id = cid;
  return null;
end $$;
drop trigger if exists ratings_counters on public.ratings;
create trigger ratings_counters after insert or update or delete on public.ratings
  for each row execute function public.refresh_challenge_counters();
drop trigger if exists comments_counters on public.comments;
