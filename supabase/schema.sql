  steps          text[] not null check (cardinality(steps) between 1 and 50),
  prep_minutes   integer check (prep_minutes between 1 and 1440),
  servings       integer check (servings between 1 and 50),
  difficulty     text not null default 'media' check (difficulty in ('facil', 'media', 'dificil')),
  image_path     text,
  is_public      boolean not null default true,
  avg_rating     numeric(3, 2) not null default 0,
  rating_count   integer not null default 0,
  comment_count  integer not null default 0,
