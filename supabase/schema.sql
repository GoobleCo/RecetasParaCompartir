-- Cada usuario sólo puede subir/borrar archivos dentro de su carpeta: <su-id>/archivo.jpg
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('recipe-images', 'recipe-images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp']),
  ('avatars',       'avatars',       true, 2097152, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

drop policy if exists "sazon leer imagenes"        on storage.objects;
drop policy if exists "sazon subir a mi carpeta"   on storage.objects;
drop policy if exists "sazon reemplazar mis archivos" on storage.objects;
drop policy if exists "sazon borrar mis archivos"  on storage.objects;

create policy "sazon leer imagenes" on storage.objects
  for select to authenticated using (bucket_id in ('recipe-images', 'avatars'));
create policy "sazon subir a mi carpeta" on storage.objects
  for insert to authenticated with check (
    bucket_id in ('recipe-images', 'avatars') and (storage.foldername(name))[1] = auth.uid()::text);
create policy "sazon reemplazar mis archivos" on storage.objects
  for update to authenticated using (
    bucket_id in ('recipe-images', 'avatars') and (storage.foldername(name))[1] = auth.uid()::text);
create policy "sazon borrar mis archivos" on storage.objects
  for delete to authenticated using (
    bucket_id in ('recipe-images', 'avatars')
    and ((storage.foldername(name))[1] = auth.uid()::text
         or (bucket_id = 'recipe-images' and public.is_staff())));

