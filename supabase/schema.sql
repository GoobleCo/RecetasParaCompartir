-- 5.1 Crear el perfil automáticamente al registrarse (email o GitHub/Google)
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  base  text;
  candidate text;
  meta  jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  base := lower(coalesce(meta ->> 'username', meta ->> 'user_name', meta ->> 'preferred_username',
                         split_part(coalesce(new.email, ''), '@', 1), ''));
  base := regexp_replace(base, '[^a-z0-9_]', '', 'g');
  base := left(base, 15);
  if char_length(base) < 3 then base := 'cocinero'; end if;
  candidate := base;
  while exists (select 1 from public.profiles where username = candidate) loop
    candidate := left(base, 15) || '_' || substr(md5(random()::text), 1, 4);
  end loop;

  insert into public.profiles (id, username, full_name, avatar_url)
  values (
    new.id,
    candidate,
    left(coalesce(meta ->> 'full_name', meta ->> 'name'), 60),
    meta ->> 'avatar_url'
  );
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

