$$;

create or replace function public.set_user_role(p_user uuid, p_role public.user_role)
returns void language plpgsql security definer set search_path = '' as $$
declare old_role public.user_role;
begin
  if not public.is_admin() then
    raise exception 'Solo un administrador puede cambiar roles' using errcode = '42501';
  end if;
  if p_user = auth.uid() then raise exception 'No podés cambiar tu propio rol' using errcode = '42501'; end if;
  select role into old_role from public.profiles where id = p_user;
  if old_role is null then raise exception 'Usuario inexistente' using errcode = 'P0002'; end if;
  if old_role = p_role then return; end if;
  update public.profiles set role = p_role where id = p_user;
  insert into public.notifications (user_id, actor_id, type, title, body)
  values (p_user, auth.uid(), 'role', 'Tu rol cambió 🔑',
          'Ahora sos ' || case p_role when 'admin' then 'administrador/a'
                                      when 'moderator' then 'moderador/a' else 'usuario/a' end);
end $$;

-- Posición de un usuario en una tabla
create or replace function public.my_rank(p_board text)
returns json language sql stable security definer set search_path = '' as $$
  select json_build_object(
    'score', b.score,
    'rank', case when b.score is null then null
                 else 1 + (select count(*) from public.best_scores x where x.board = p_board and x.score > b.score) end,
    'total', (select count(*) from public.best_scores x where x.board = p_board))
  from (select (select score from public.best_scores where user_id = auth.uid() and board = p_board) as score) b;
$$;

-- Resumen para la pantalla de inicio
create or replace function public.home_stats()
returns json language plpgsql stable security definer set search_path = '' as $$
declare uid uuid := auth.uid(); d date := public.game_today(); best int; daily int;
begin
  select score into best  from public.best_scores where user_id = uid and board = 'classic';
  select score into daily from public.best_scores where user_id = uid and board = 'daily:' || d::text;
  return json_build_object(
    'best_classic', best,
    'classic_rank', case when best is null then null
                    else 1 + (select count(*) from public.best_scores where board = 'classic' and score > best) end,
    'daily_best', daily,
    'daily_rank', case when daily is null then null
                  else 1 + (select count(*) from public.best_scores where board = 'daily:' || d::text and score > daily) end,
    'week', public.game_week(d),
    'today', d,
    'games_played', (select count(*) from public.runs where user_id = uid and status = 'finished'),
    'my_challenges', (select count(*) from public.challenges where author_id = uid),
    'followers', (select count(*) from public.follows where following_id = uid),
    'unread', (select count(*) from public.notifications where user_id = uid and not read));
end $$;

