-- SECURITY DEFINER: corren con permisos del dueño (leen el rol sin recursión de RLS).
-- search_path = '' evita que alguien "suplante" funciones o tablas.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select role = 'admin' from public.profiles where id = auth.uid()), false);
$$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select role in ('admin', 'moderator') from public.profiles where id = auth.uid()), false);
$$;

create or replace function public.can_view_challenge(cid uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.challenges c
    where c.id = cid and (c.is_public or c.author_id = auth.uid() or public.is_staff())
  );
$$;

