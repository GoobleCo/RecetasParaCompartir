-- 5.3 Contadores (promedio de estrellas, comentarios, favoritos)
create or replace function public.refresh_recipe_counters()
returns trigger language plpgsql security definer set search_path = '' as $$
declare rid uuid := coalesce(new.recipe_id, old.recipe_id);
begin
  update public.recipes r set
    avg_rating     = coalesce((select round(avg(stars)::numeric, 2) from public.ratings where recipe_id = rid), 0),
    rating_count   = (select count(*) from public.ratings   where recipe_id = rid),
    comment_count  = (select count(*) from public.comments  where recipe_id = rid),
    favorite_count = (select count(*) from public.favorites where recipe_id = rid)
  where r.id = rid;
  return null;
end $$;

drop trigger if exists ratings_counters on public.ratings;
create trigger ratings_counters after insert or update or delete on public.ratings
  for each row execute function public.refresh_recipe_counters();
drop trigger if exists comments_counters on public.comments;
create trigger comments_counters after insert or delete on public.comments
  for each row execute function public.refresh_recipe_counters();
drop trigger if exists favorites_counters on public.favorites;
create trigger favorites_counters after insert or delete on public.favorites
  for each row execute function public.refresh_recipe_counters();

-- 5.4 Notificaciones por eventos reales de la app
create or replace function public.notify_on_comment()
returns trigger language plpgsql security definer set search_path = '' as $$
declare rec record; actor text;
begin
  select r.id, r.title, r.author_id, p.notify_comments into rec
  from public.recipes r join public.profiles p on p.id = r.author_id where r.id = new.recipe_id;
  if rec.author_id is null or rec.author_id = new.user_id or not rec.notify_comments then return new; end if;
  select username into actor from public.profiles where id = new.user_id;
  insert into public.notifications (user_id, actor_id, type, title, body, recipe_id)
  values (rec.author_id, new.user_id, 'comment', 'Nuevo comentario 💬',
          '@' || actor || ' comentó "' || rec.title || '": ' || left(new.body, 80), rec.id);
  return new;
end $$;
drop trigger if exists comments_notify on public.comments;
create trigger comments_notify after insert on public.comments
  for each row execute function public.notify_on_comment();

create or replace function public.notify_on_rating()
returns trigger language plpgsql security definer set search_path = '' as $$
declare rec record; actor text;
begin
  if tg_op = 'UPDATE' and new.stars = old.stars then return new; end if;
  select r.id, r.title, r.author_id, p.notify_ratings into rec
  from public.recipes r join public.profiles p on p.id = r.author_id where r.id = new.recipe_id;
  if rec.author_id is null or rec.author_id = new.user_id or not rec.notify_ratings then return new; end if;
  select username into actor from public.profiles where id = new.user_id;
  insert into public.notifications (user_id, actor_id, type, title, body, recipe_id)
  values (rec.author_id, new.user_id, 'rating', 'Nueva valoración ⭐',
          '@' || actor || ' le dio ' || new.stars || ' estrella' || case when new.stars = 1 then '' else 's' end
          || ' a "' || rec.title || '"', rec.id);
  return new;
end $$;
drop trigger if exists ratings_notify on public.ratings;
create trigger ratings_notify after insert or update on public.ratings
  for each row execute function public.notify_on_rating();

create or replace function public.notify_on_follow()
returns trigger language plpgsql security definer set search_path = '' as $$
declare actor text; wants boolean;
begin
  select notify_follows into wants from public.profiles where id = new.following_id;
  if not coalesce(wants, false) then return new; end if;
  select username into actor from public.profiles where id = new.follower_id;
  insert into public.notifications (user_id, actor_id, type, title, body)
  values (new.following_id, new.follower_id, 'follow', 'Nuevo seguidor 👋',
          '@' || actor || ' empezó a seguirte');
  return new;
end $$;
drop trigger if exists follows_notify on public.follows;
create trigger follows_notify after insert on public.follows
  for each row execute function public.notify_on_follow();

create or replace function public.notify_on_new_recipe()
returns trigger language plpgsql security definer set search_path = '' as $$
declare actor text;
begin
  if not new.is_public then return new; end if;
  select username into actor from public.profiles where id = new.author_id;
  insert into public.notifications (user_id, actor_id, type, title, body, recipe_id)
  select f.follower_id, new.author_id, 'new_recipe', 'Receta nueva 🍳',
         '@' || actor || ' publicó "' || new.title || '"', new.id
  from public.follows f join public.profiles p on p.id = f.follower_id
  where f.following_id = new.author_id and p.notify_new_recipes;
  return new;
end $$;
drop trigger if exists recipes_notify on public.recipes;
create trigger recipes_notify after insert on public.recipes
  for each row execute function public.notify_on_new_recipe();

-- 6. PUSH: cada notificación insertada se envía al celular -------------
-- pg_net hace el POST de forma ASÍNCRONA (no bloquea la operación del usuario).
create or replace function public.push_notification()
returns trigger language plpgsql security definer set search_path = '' as $$
declare msgs jsonb;
begin
  select jsonb_agg(jsonb_build_object(
           'to', t.token,
           'title', new.title,
           'body', new.body,
           'sound', 'default',
           'channelId', 'default',
           'data', jsonb_build_object(
             'notificationId', new.id,
             'type', new.type,
             'recipeId', new.recipe_id,
             'actorId', new.actor_id)))
    into msgs
  from public.push_tokens t where t.user_id = new.user_id;

  if msgs is not null then
    perform net.http_post(
      url     := 'https://exp.host/--/api/v2/push/send',
      body    := msgs,
      headers := '{"Content-Type": "application/json", "Accept": "application/json"}'::jsonb
    );
  end if;
  return new;
exception when others then
  -- Si el envío falla, la notificación igual queda guardada en la app.
  raise warning 'No se pudo enviar el push: %', sqlerrm;
  return new;
end $$;
drop trigger if exists notifications_push on public.notifications;
create trigger notifications_push after insert on public.notifications
  for each row execute function public.push_notification();

-- 7. PROCESOS EN SEGUNDO PLANO (pg_cron) --------------------------------
-- 7.1 "Receta del día": todos los días a las 11:00 (Argentina, UTC-3 = 14:00 UTC)
create or replace function public.send_daily_recipe()
returns integer language plpgsql security definer set search_path = '' as $$
declare rec record; sent integer;
begin
  select r.id, r.title, r.author_id into rec
  from public.recipes r
  where r.is_public
  order by (r.created_at > now() - interval '30 days') desc,
           r.avg_rating * ln(r.rating_count + 2) + r.favorite_count * 0.3 desc,
           random()
  limit 1;
  if rec.id is null then return 0; end if;

  insert into public.notifications (user_id, actor_id, type, title, body, recipe_id)
  select p.id, rec.author_id, 'daily', 'Receta del día 🍽️', '¿Qué tal hoy "' || rec.title || '"?', rec.id
  from public.profiles p
  where p.notify_daily and p.id <> rec.author_id;
  get diagnostics sent = row_count;
  return sent;
end $$;

-- 7.2 Limpieza semanal: notificaciones leídas viejas y tokens abandonados
create or replace function public.cleanup_old_data()
returns void language plpgsql security definer set search_path = '' as $$
begin
  delete from public.notifications where read and created_at < now() - interval '30 days';
  delete from public.notifications where created_at < now() - interval '120 days';
  delete from public.push_tokens   where updated_at < now() - interval '90 days';
end $$;

revoke execute on function public.send_daily_recipe() from public, anon, authenticated;
revoke execute on function public.cleanup_old_data() from public, anon, authenticated;

select cron.schedule('sazon-receta-del-dia', '0 14 * * *', 'select public.send_daily_recipe()');
select cron.schedule('sazon-limpieza-semanal', '0 6 * * 0', 'select public.cleanup_old_data()');

-- 8. RPC (funciones que llama la app) ----------------------------------
create or replace function public.username_available(p_username text)
returns boolean language sql stable security definer set search_path = '' as $$
  select not exists (select 1 from public.profiles where username = lower(p_username));
$$;
grant execute on function public.username_available(text) to anon, authenticated;

create or replace function public.register_push_token(p_token text, p_platform text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'No autenticado' using errcode = '42501'; end if;
  if p_token is null or p_token !~ '^Expo(nent)?PushToken\[.+\]$' then
    raise exception 'Token push inválido' using errcode = '22023';
  end if;
  insert into public.push_tokens (token, user_id, platform, updated_at)
  values (p_token, auth.uid(), p_platform, now())
  on conflict (token) do update set user_id = excluded.user_id, platform = excluded.platform, updated_at = now();
end $$;

create or replace function public.unregister_push_token(p_token text)
returns void language sql security definer set search_path = '' as $$
  delete from public.push_tokens where token = p_token and user_id = auth.uid();
$$;

-- Cambiar el rol de un usuario: SOLO admin, controlado en el backend.
create or replace function public.set_user_role(p_user uuid, p_role public.user_role)
returns void language plpgsql security definer set search_path = '' as $$
declare old_role public.user_role;
begin
  if not public.is_admin() then
    raise exception 'Solo un administrador puede cambiar roles' using errcode = '42501';
  end if;
  if p_user = auth.uid() then
    raise exception 'No podés cambiar tu propio rol' using errcode = '42501';
  end if;
  select role into old_role from public.profiles where id = p_user;
  if old_role is null then raise exception 'Usuario inexistente' using errcode = 'P0002'; end if;
  if old_role = p_role then return; end if;
  update public.profiles set role = p_role where id = p_user;
  insert into public.notifications (user_id, actor_id, type, title, body)
  values (p_user, auth.uid(), 'role', 'Tu rol cambió 🔑',
          'Ahora sos ' || case p_role when 'admin' then 'administrador/a'
                                      when 'moderator' then 'moderador/a' else 'usuario/a' end);
end $$;

-- Resumen para la pantalla de inicio
create or replace function public.home_stats()
returns json language sql stable security definer set search_path = '' as $$
  select json_build_object(
    'my_recipes', (select count(*) from public.recipes   where author_id = auth.uid()),
    'favorites',  (select count(*) from public.favorites where user_id = auth.uid()),
    'followers',  (select count(*) from public.follows   where following_id = auth.uid()),
    'following',  (select count(*) from public.follows   where follower_id = auth.uid()),
    'unread',     (select count(*) from public.notifications where user_id = auth.uid() and not read),
    'total_recipes', (select count(*) from public.recipes where is_public)
  );
$$;

-- Borrar la propia cuenta (privacidad)
create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'No autenticado' using errcode = '42501'; end if;
  delete from auth.users where id = auth.uid();
end $$;

