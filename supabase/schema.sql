-- 8.2 Avisar a las 11:00 a quienes todavía no jugaron el diario
create or replace function public.notify_daily_challenge()
returns integer language plpgsql security definer set search_path = '' as $$
declare d date := public.game_today(); n integer;
begin
  perform public.ensure_daily_challenge(d);
  insert into public.notifications (user_id, type, title, body)
  select p.id, 'daily', 'Desafío diario listo 📡', 'Hay una nueva secuencia para hoy. ¿Llegás al top 10?'
  from public.profiles p
  where p.notify_daily
    and not exists (select 1 from public.runs r where r.user_id = p.id and r.mode = 'daily' and r.day = d);
  get diagnostics n = row_count;
  return n;
end $$;

-- 8.3 Premios semanales: el lunes avisa al podio de la semana anterior
create or replace function public.weekly_awards()
returns integer language plpgsql security definer set search_path = '' as $$
declare wk text := public.game_week(public.game_today() - 7); n integer;
begin
  insert into public.notifications (user_id, type, title, body)
  select t.user_id, 'weekly',
         case t.pos when 1 then '🥇 ¡Ganaste la semana!' when 2 then '🥈 Segundo puesto semanal' else '🥉 Tercer puesto semanal' end,
         'Terminaste #' || t.pos || ' del ranking semanal con ' || t.score || ' puntos.'
  from (select user_id, score, row_number() over (order by score desc, achieved_at) as pos
        from public.best_scores where board = 'classic:week:' || wk) t
  where t.pos <= 3;
  get diagnostics n = row_count;
  return n;
end $$;

